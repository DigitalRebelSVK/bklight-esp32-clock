#!/usr/bin/env python3
"""Convert the X11 misc-fixed 5x8 BDF font into src/font5x8.h.

Only the glyphs the clock needs are kept: printable ASCII, the degree sign,
Slovak/Czech/German letters and a few typographic characters that iOS likes to
put into calendar titles (curly quotes, dashes, ellipsis).

Usage: python3 tools/gen_font.py path/to/5x8.bdf src/font5x8.h
The font is public domain (X11 misc-fixed).
"""
import sys

EXTRA = (
    "°ÁáÄäČčĎďÉéĚěÍíĹĺĽľŇňÓóÔôÖöŔŕŘřŠšŤťÚúŮůÜüÝýŽž"
    "–—‘’“”…·"
)
WANTED = sorted(set(range(32, 127)) | {ord(c) for c in EXTRA})

# misc-fixed 5x8 has a 4-row x-height and its 'e' and 's' turn into blobs on a
# LED matrix. Replace their bodies (rows 3..6) - also in the accented forms.
BODY_OVERRIDE = {
    "e": [0x60, 0xF0, 0x80, 0x70],
    "s": [0x70, 0xC0, 0x30, 0xE0],
}
BODY_USERS = {"e": "eéěëè", "s": "sšś"}

# Whole-glyph replacements. The original '0' is a 3 px oval, narrower than
# every other digit; this one is 4 px like the rest. The minus is 3 px
# instead of 4 so the temperature reads tighter.
GLYPH_OVERRIDE = {
    "0": [0x00, 0x60, 0x90, 0x90, 0x90, 0x90, 0x60, 0x00],
    "-": [0x00, 0x00, 0x00, 0x00, 0x70, 0x00, 0x00, 0x00],  # 3 px, centred
}


def apply_overrides(glyphs):
    for ch, rows in GLYPH_OVERRIDE.items():
        bbx, _ = glyphs[ord(ch)]
        glyphs[ord(ch)] = (bbx, list(rows))
    for base, body in BODY_OVERRIDE.items():
        for ch in BODY_USERS[base]:
            cp = ord(ch)
            if cp in glyphs:
                bbx, rows = glyphs[cp]
                rows = list(rows)
                rows[3:7] = body
                glyphs[cp] = (bbx, rows)


def parse_bdf(path):
    glyphs = {}
    enc = None
    bbx = None
    rows = None
    with open(path, encoding="latin-1") as fh:
        for line in fh:
            parts = line.split()
            if not parts:
                continue
            key = parts[0]
            if key == "ENCODING":
                enc = int(parts[1])
            elif key == "BBX":
                bbx = tuple(int(p) for p in parts[1:5])
            elif key == "BITMAP":
                rows = []
            elif key == "ENDCHAR":
                if enc is not None and rows is not None:
                    glyphs[enc] = (bbx, rows)
                enc, bbx, rows = None, None, None
            elif rows is not None:
                rows.append(int(parts[0], 16))
    return glyphs


def main():
    src, dst = sys.argv[1], sys.argv[2]
    glyphs = parse_bdf(src)
    apply_overrides(glyphs)
    out = []
    missing = []
    for cp in WANTED:
        if cp not in glyphs:
            missing.append(cp)
            continue
        bbx, rows = glyphs[cp]
        if bbx != (5, 8, 0, -1) or len(rows) != 8:
            raise SystemExit(f"unexpected glyph box for U+{cp:04X}: {bbx}")
        out.append((cp, rows))
    if missing:
        print("missing:", " ".join(f"U+{m:04X}" for m in missing), file=sys.stderr)

    lines = [
        "// Generated by tools/gen_font.py from X11 misc-fixed 5x8 (public domain),",
        "// with redrawn lowercase e/s bodies and a full-width 0.",
        "// Each glyph: 8 rows, MSB = leftmost pixel, 5 px wide incl. 1 px spacing.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "namespace font5x8 {",
        "constexpr int kAdvance = 5;",
        "constexpr int kHeight = 8;",
        "constexpr int kAscent = 7;",
        f"constexpr int kCount = {len(out)};",
        "// Sorted by code point for binary search.",
        "static const uint16_t kCodes[kCount] = {",
    ]
    for i in range(0, len(out), 12):
        chunk = out[i:i + 12]
        lines.append("  " + ", ".join(f"0x{cp:04X}" for cp, _ in chunk) + ",")
    lines.append("};")
    lines.append("static const uint8_t kRows[kCount][8] = {")
    for cp, rows in out:
        ch = chr(cp)
        label = ch if cp > 32 and ch not in "\\" else f"U+{cp:04X}"
        body = ", ".join(f"0x{r:02X}" for r in rows)
        lines.append("  {" + body + "},  // " + label)
    lines.append("};")
    lines.append("}  // namespace font5x8")
    lines.append("")
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {len(out)} glyphs to {dst}")


if __name__ == "__main__":
    main()
